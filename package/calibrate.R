#' Number of constraints satisfied.
#' 
#' How many inputs pass N/k constraints.
#'
#' @param impl Matrix of implausibilities, with each row corresponding to an input vector, and each column corresponding to an output.
#' @param threshold Threshold to use for defining NROY space. Defaults to 3.
#'
#' @returns Proportion of inputs that satisfy N = 0,1,...k of the k constraints.
#' @export
#'
#' @examples
pass_metric <- function(impl, threshold = 3){
  ns <- nrow(impl)
  summary(as.factor(apply(impl < threshold, 1, sum, na.rm = TRUE))) / ns
}



#' 1D implausibility
#'
#' Calculates the 1D implausibility for 1 or more metrics
#'
#' @param Predictions A list containing components `$Expectation` and `$Variance`, where each provide the emulator expectation/variance for a set of inputs, where the rows contains the expectations/variances for different inputs, and the columns contain different outputs. The output of `Predict` can be provided here.
#' @param Obs The observations. Can be a single value or a vector. Its length needs to match the number of columns in `Predictions$Expectations`.
#' @param ObsVar Observation error variance. If a single value is provided, assumes the observation error is constant and uncorrelated across all outputs provided in `Obs`. Else should be a vector with the same length as `Obs`.
#' @param DiscVar Discrepancy variance. Defaults to zero as this may be included in `ObsVar`. The same rules apply as for providing `ObsVar`. 
#' @param kmax Which kth-max implausibility to use to define NROY space. Defaults to 1 (i.e. use the maximum implausibility across all outputs to classify an input).
#' @param threshold Threshold to use for defining NROY space. Defaults to 3.
#'
#' @returns \item{Impl}{The implausibility for each input, corresponding to the rows of `design`. If calculating multiple implausibilities, output is a matrix with the corresponding number of columns.}
#' \item{threshold}{The implausibility threshold T that was used to define NROY space.}
#' \item{NROY}{The proportion of points that are in NROY space.}
#' \item{inNROY}{A logical vector indicating which points are in NROY space.}
#' \item{Pass_kth}{The proportion of points that are in each marginal NROY, i.e. according to each observation independently.}
#' \item{Pass_N}{The proportion of points that are in the marginal NROY space for N of the k provided constraints, for N=0,...k.}
#'
#' @export
Impl <- function(Predictions, Obs, ObsVar, DiscVar = 0, kmax = 1, threshold = 3){

  Expectation <- Predictions$Expectation
  Variance <- Predictions$Variance
  
  # Number of outputs
  ell <- ncol(Expectation)
  
  # Number of prediction points
  n <- nrow(Expectation)

  if (is.null(ell)){
    ell <- 1
  }
  
  if (!(length(Obs) == ell)){
    stop('Inconsistency between number of emulator predictions and number of observations provided')
  }
  
  if (!(length(ObsVar) %in% c(1,ell))){
    stop('Inconsistency between number of emulator predictions and number of observation error variances provided')
  }
  
  if (length(ObsVar) == 1 & !(ell == 1)){
    ObsVar <- rep(ObsVar, ell)
  }
  
  if (!(length(DiscVar) %in% c(1,ell))){
    stop('Inconsistency between number of emulator predictions and number of discrepancy variances provided')
  }
  
  if (length(DiscVar) == 1 & !(ell == 1)){
    DiscVar <- rep(DiscVar, ell)
  }
  
  # Converting to vector
  Obs <- as.numeric(Obs)
  
  # Calculate implausibility
  impl <- parallel::mclapply(1:ell, 
                             function(k) Impl1D(Expectation[,k], Variance[,k], Obs[k], ObsVar[k], DiscVar[k]),
                             mc.cores = n_cores)
  impl <- matrix(unlist(impl), n, ell)

  # Proportion of samples that pass each metric individually
  pass_kth <- pass_kth_metric(impl, threshold)
  
  # Number of constraints passed by each sample
  pass_N <- pass_metric(impl, threshold)
  
  # Defining NROY based on kmax
  impl_kmax <- apply(impl, 1, kth_max, k = kmax)
  nroy <- mean(impl_kmax < threshold)
  inNROY <- impl_kmax < threshold

  return(list(Impl = impl,
              threshold = threshold,
              NROY = nroy,
              Pass_kth = pass_kth,
              Pass_N = pass_N,
              inNROY = inNROY))
}






#' Title
#'
#' @param expectation 
#' @param variance 
#' @param Obs 
#' @param ObsVar 
#' @param DiscVar 
#'
#' @returns
#'
#' @examples
Impl1D <- function(expectation, variance, Obs, ObsVar, DiscVar = 0){
  abs(expectation - Obs) / sqrt(variance + ObsVar + DiscVar)
}






#' Generate a design in NROY
#' 
#' Given a set of points in the current NROY space (or otherwise), finds a space-filling sample of a given size.
#'
#' @param CandidatePoints A matrix of input vectors to select the new design from. Each row corresponds to different points, each column to different input dimensions.
#' @param n_new The size of the new design.
#' @param reps How many sample designs to assess. Defaults to 100.
#'
#' @returns \item{design}{The selected space-filling design.}
#' \item{inds}{Indices relating to which rows of `CandidatePoints` were selected.}
#' 
#' @export
#'
#' @examples
NewDesign <- function(CandidatePoints, n_new, reps = 100){
  
  # If final column(s) of CandidatePoints are NROY indicator, remove
  nroy_inds <- grep('NROY', colnames(CandidatePoints))
  
  if (length(nroy_inds) > 0){
    CandidatePoints <- CandidatePoints[,-nroy_inds]
  }
  
  # Generate candidate designs of size n_new
  inds_list <- NULL
  dist_min <- numeric(reps)
  for (i in 1:reps){
    inds_list[[i]] <- sample(1:nrow(CandidatePoints), n_new)
    tmp_design <- CandidatePoints[inds_list[[i]],]
    dists <- fields::rdist(tmp_design)
    diag(dists) <- NA
    dist_min[i] <- min(c(dists), na.rm = TRUE)
    rm(dists)
  }
  
  k <- which.max(dist_min)
  
  new_design <- CandidatePoints[inds_list[[k]],]
  
  rownames(new_design) <- NULL
  
  return(list(design = new_design,
              inds = inds_list[[k]]))
}




